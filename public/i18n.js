  function normalize(locale) {
    return locale === 'en' ? 'en' : 'zh';
  }

  function format(template, params) {
    return template.replace(/\{(\w+)\}/g, (match, key) => (params && params[key] !== undefined ? String(params[key]) : match));
  }

  function t(locale, key, params = {}) {
    const dictionary = DICTIONARIES[normalize(locale)];
    const template = dictionary[key] !== undefined ? dictionary[key] : (DICTIONARIES.zh[key] !== undefined ? DICTIONARIES.zh[key] : key);
    return format(template, params);
  }

  function detect() {
    try {
      const saved = localStorage.getItem('ecommerce-content-assistant-locale');
      if (saved === 'zh' || saved === 'en') return saved;
    } catch {
      // Ignore storage failures.
    }
    return typeof navigator !== 'undefined' && String(navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  function applyStatic(root, locale) {
    for (const element of root.querySelectorAll('[data-i18n]')) {
      element.textContent = t(locale, element.dataset.i18n);
    }
    for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
      element.setAttribute('placeholder', t(locale, element.dataset.i18nPlaceholder));
    }
    for (const element of root.querySelectorAll('[data-i18n-aria-label]')) {
      element.setAttribute('aria-label', t(locale, element.dataset.i18nAriaLabel));
    }
    for (const element of root.querySelectorAll('[data-i18n-title]')) {
      element.setAttribute('title', t(locale, element.dataset.i18nTitle));
    }
  }

  window.APP_I18N = { DICTIONARIES, applyStatic, detect, normalize, t };
